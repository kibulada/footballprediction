TEAMS = [f"T{i}" for i in range(8)]


def _synthetic_fixtures(n: int = 160) -> list[dict]:
    """Deterministic synthetic league: T0 beats everyone, others roughly even.

    Home win prob ~0.5, draw ~0.26, away ~0.24 to mimic base rates.
    """
    import random

    rng = random.Random(42)
    fixtures = []
    day = 0
    for i in range(n):
        home, away = rng.sample(TEAMS, 2)
        day += 1
        strength_h = 1.0 + (5 - int(home[1])) * 0.08   # T0 strongest
        strength_a = 1.0 + (5 - int(away[1])) * 0.08
        roll = rng.random()
        if roll < 0.46 * strength_h / (strength_h + strength_a) * 2:
            hg, ag = rng.randint(1, 3), rng.randint(0, 2)
        elif roll < 0.72:
            hg, ag = rng.randint(0, 1), rng.randint(0, 1)
        else:
            hg, ag = rng.randint(0, 2), rng.randint(1, 3)
        if hg == ag and rng.random() < 0.3:
            ag += 1  # break ties sometimes
        if hg == ag and rng.random() < 0.3:
            hg += 1
        fixtures.append(
            {
                "date": f"2025-{1 + day // 28:02d}-{1 + day % 27:02d}",
                "home": home,
                "away": away,
                "home_goals": hg,
                "away_goals": ag,
                "league": "SYN",
                "home_odds": 2.0, "draw_odds": 3.4, "away_odds": 3.6,
            }
        )
    return fixtures


def test_synthetic_data_shapes():
    fixtures = _synthetic_fixtures()
    assert len(fixtures) == 160
    assert all(f["date"] <= "2025-12-31" for f in fixtures)


def test_run_backtest_metrics_computed():
    fixtures = _synthetic_fixtures()
    result = run_backtest(fixtures)
    assert result["n_matches"] == len(fixtures)
    m = result["metrics"]
    for name in ("baseline", "elo", "poisson", "ensemble"):
        assert name in m
        assert m[name]["n"] > 0
        assert 0 < m[name]["log_loss"] <= 2.0  # log-loss is positive & finite
        assert 0 < m[name]["brier"] <= 2.0
        assert 0 <= m[name]["hit_rate"] <= 1.0
        assert m[name]["roi"] is not None  # odds present in synthetic data


def test_ensemble_not_worse_than_random_baseline():
    """Sanity: on a skill-structured dataset the ensemble should beat the
    base-rate baseline on hit rate (not a claim of real-world accuracy)."""
    fixtures = _synthetic_fixtures()
    result = run_backtest(fixtures)
    m = result["metrics"]
    assert m["ensemble"]["hit_rate"] >= m["baseline"]["hit_rate"] - 0.05


def test_no_leakage_walk_forward():
    """A model must never see the match it is predicting. We verify by
    checking that the first matches (no prior history) have no poisson
    contribution and that elo ratings only move after replay."""
    fixtures = _synthetic_fixtures()
    result = run_backtest(fixtures)
    assert result["n_matches"] == len(fixtures)
    # poisson should have fewer evaluated matches than elo (needs >=1 prior
    # match per team for form features)
    assert result["metrics"]["poisson"]["n"] <= result["metrics"]["elo"]["n"]


