def test_lambda_from_mode_pinned_is_production_default():
    """P1.4: the production default lambda mode is "pinned" -- the default
    arg of both lambda_from_mode and run_prediction_engine must reflect it,
    and config/football.json must carry the inspectable flag."""
    import inspect
    import json
    from pathlib import Path

    from agents.football.models import lambda_from_mode, run_prediction_engine

    # Engine default flipped to pinned (P1.4) -- NOT threshold.
    sig = inspect.signature(run_prediction_engine)
    assert sig.parameters["lambda_mode"].default == "pinned"
    sig2 = inspect.signature(lambda_from_mode)
    assert sig2.parameters["mode"].default == "pinned"

    # Inspectable config flag: models.poisson.lambda_mode == "pinned".
    cfg = json.loads(
        (Path(__file__).resolve().parent.parent / "config" / "football.json")
        .read_text(encoding="utf-8")
    )
    assert (cfg["models"]["poisson"].get("lambda_mode") or "pinned") == "pinned"

    # The pinned fallback (no pin state in a single query) matches threshold.
    kw = dict(lh_e=1.1, la_e=1.9, lh_f=1.6, la_f=1.2, samples=0,
              min_samples=2, shrinkage=5, rho=-0.1)
    rp = lambda_from_mode(mode="pinned", **kw)
    rt = lambda_from_mode(mode="threshold", **kw)
    assert rp == rt


def test_lambda_from_mode_threshold_matches_production_branches():
    """The pure helper reproduces the production threshold logic exactly:
    samples < min -> pure elo; min <= samples < shrinkage -> blend;
    samples >= shrinkage -> features as-is."""
    from agents.football.models import lambda_from_mode

    # below min_samples -> elo
    r = lambda_from_mode(lh_e=1.1, la_e=1.9, lh_f=1.6, la_f=1.2, samples=0,
                         min_samples=2, shrinkage=5, rho=-0.1)
    assert r["lambda_source"] == "elo"
    assert r["lambda_home"] == 1.1 and r["lambda_away"] == 1.9
    # in the blend band -> features+elo
    r = lambda_from_mode(lh_e=1.1, la_e=1.9, lh_f=1.6, la_f=1.2, samples=3,
                         min_samples=2, shrinkage=5, rho=-0.1)
    assert r["lambda_source"] == "features+elo"
    assert abs(r["lambda_home"] - (1.6 * (1 / 3) + 1.1 * (2 / 3))) < 1e-9
    # at/above shrinkage -> features
    r = lambda_from_mode(lh_e=1.1, la_e=1.9, lh_f=1.6, la_f=1.2, samples=5,
                         min_samples=2, shrinkage=5, rho=-0.1)
    assert r["lambda_source"] == "features"
    assert r["lambda_home"] == 1.6


def test_lambda_from_mode_blend_never_switches_estimator():
    """Option 3: blend always mixes feature+elo by sample count -- the λ is a
    smooth function of samples, never a hard elo/features switch."""
    from agents.football.models import lambda_from_mode

    def _lam(samples):
        return lambda_from_mode(lh_e=1.0, la_e=2.0, lh_f=1.6, la_f=1.2, samples=samples,
                                min_samples=2, shrinkage=5, rho=-0.1, mode="blend")

    l0 = _lam(0)["lambda_home"]
    l2 = _lam(2)["lambda_home"]
    l3 = _lam(3)["lambda_home"]
    l5 = _lam(5)["lambda_home"]
    assert l0 == 1.0                      # zero samples -> pure elo
    assert l5 == 1.6                      # >= target -> full features
    assert l0 <= l2 < l3 < l5             # monotone non-decreasing ramp, no cliff
    assert abs(l2 - (1.0 + 0.6 * (2 / 5))) < 1e-9
    for s in (0, 1, 2, 3, 5, 8):
        assert _lam(s)["lambda_source"] == "features+elo"


