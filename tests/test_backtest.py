def test_ensemble_weights_flow_into_backtest():
    """The ensemble config must actually change the replayed ensemble row
    (weights are not ignored): elo-only and poisson-only ensembles diverge on
    the skill-structured synthetic league."""
    fixtures = _synthetic_fixtures(160)
    elo_only = run_backtest(
        fixtures, ensemble_cfg={"elo_weight": 1.0, "poisson_weight": 0.0}
    )
    pois_only = run_backtest(
        fixtures, ensemble_cfg={"elo_weight": 0.0, "poisson_weight": 1.0}
    )
    assert elo_only["metrics"]["ensemble"]["log_loss"] != pois_only["metrics"]["ensemble"]["log_loss"]


def test_p4_weights_retained_decision_pinned():
    """P4 backtest decision lock: the cross-validated A/B (reports/p4_weights_backtest.md)
    showed current ensemble weights 0.7/0.3 are the only config with positive ROI in
    BOTH non-overlapping periods (0.5/0.5 goes negative in period B), and movement/
    late_movement weights are retained because no historical opening->latest movement
    data exists to validate them. This test pins that decision so a future re-tune
    must come with fresh evidence, not a silent edit."""
    from agents.football.backtest import _load_model_config
    from agents.football.signal_engine import DEFAULT_WEIGHTS

    # 1. Production ensemble weights stay at the cross-validated 0.7/0.3.
    elo_cfg, _, ensemble_cfg = _load_model_config()
    assert ensemble_cfg.get("elo_weight") == 0.6
    assert ensemble_cfg.get("poisson_weight") == 0.4

    # 2. Weight distribution v3: rebalanced for market intelligence.
    # model 0.35, statistical 0.10, market 0.15 (2026-08-19 reweight),
    # market_intelligence 0.15, movement 0.15, data_quality 0.05.
    assert DEFAULT_WEIGHTS["movement"] == 0.15
    assert DEFAULT_WEIGHTS["late_movement"] == 0.00
    assert DEFAULT_WEIGHTS["model"] == 0.35
    assert DEFAULT_WEIGHTS["statistical"] == 0.10
    assert DEFAULT_WEIGHTS["market"] == 0.15
    assert DEFAULT_WEIGHTS["market_intelligence"] == 0.15
    assert DEFAULT_WEIGHTS["data_quality"] == 0.05
    assert DEFAULT_WEIGHTS["team_context"] == 0.00

    # 3. The written report exists and documents the decision(s).
    report = ROOT / "reports" / "p4_weights_backtest.md"
    assert report.exists(), "P4 report missing — weights decision must be documented"
    text = report.read_text(encoding="utf-8")
    assert "No production weight change" in text
    assert "0.7/0.3" in text


