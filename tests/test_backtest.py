def test_load_fixtures_carries_prematch_xg_only():
    """The loader must preserve the pre-match rolling xG features so the
    standard harnesses can evaluate the production xG blend, but must NEVER
    carry the raw per-match home_xg/away_xg (post-match -> leakage)."""
    import json
    import tempfile

    fixtures = _synthetic_fixtures(30)
    for f in fixtures[:10]:
        f["home_xg_for"] = 1.5
        f["home_xg_against"] = 1.2
        f["away_xg_for"] = 1.1
        f["away_xg_against"] = 1.4
        f["home_xg"] = 2.0  # raw post-match xG -> must be dropped
        f["away_xg"] = 1.0
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "fx.json"
        path.write_text(json.dumps(fixtures), encoding="utf-8")
        from agents.football.backtest import load_fixtures_from_json

        loaded = load_fixtures_from_json(path)
        # The generated fixture #1 (day 1 -> "2025-01-02") is one of the
        # xG-carrying rows; the chronologically-first row (2025-01-01, day
        # 27) is not, so match on the known date.
        first = next(m for m in loaded if m["date"] == "2025-01-02")
        assert first["home_xg_for"] == 1.5
        assert first["away_xg_against"] == 1.4
        assert "home_xg" not in first  # raw columns never survive
        assert "away_xg" not in first


